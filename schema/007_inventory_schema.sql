create table if not exists public.tbl_inv_branch_settings (
  branch_id                    bigint primary key references public.tbl_branches ("BranchID"),
  is_enabled                   boolean not null default false,
  go_live_date                 date,
  opening_window_days          int not null default 7 check (opening_window_days between 0 and 31),   -- D-117
  writeoff_threshold           numeric(12,2) not null default 50.00 check (writeoff_threshold >= 0), -- D-108, Q-7
  osem_issue_review_threshold  numeric(12,2) not null default 100.00 check (osem_issue_review_threshold >= 0),
  created_at                   timestamptz not null default now(),
  updated_at                   timestamptz not null default now(),
  updated_by_account           bigint references public.tbl_user_accounts (id),
  check (not is_enabled or go_live_date is not null)
);

-- D-20/D-140: exactly one STORE, FLOOR, TRANSIT per NUR branch (guard trigger).
create table if not exists public.tbl_inv_locations (
  id                    bigint generated by default as identity primary key,
  branch_id             bigint not null references public.tbl_branches ("BranchID"),
  kind                  text not null check (kind in ('STORE','FLOOR','TRANSIT')),
  name                  text not null check (length(btrim(name)) between 1 and 60),
  count_frequency_days  int check (count_frequency_days > 0),
  is_active             boolean not null default true,
  created_at            timestamptz not null default now(),
  unique (branch_id, kind)
);

create table if not exists public.tbl_inv_stock_levels (   -- per-location override of product defaults (D-101)
  location_id         bigint not null references public.tbl_inv_locations (id),
  product_id          bigint not null references public.tbl_inv_products (id),
  branch_id           bigint not null references public.tbl_branches ("BranchID"),
  max_qty             numeric(18,4) not null check (max_qty >= 0),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  updated_by_account  bigint not null references public.tbl_user_accounts (id),
  primary key (location_id, product_id)
);
create index if not exists idx_inv_stock_levels_branch on public.tbl_inv_stock_levels (branch_id, product_id);

create table if not exists public.tbl_inv_resident_billing (   -- D-122
  resident_id         bigint primary key references public.tbl_residents (id),
  branch_id           bigint not null references public.tbl_branches ("BranchID"),
  billing_code        text not null unique check (length(btrim(billing_code)) between 1 and 40),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  updated_by_account  bigint not null references public.tbl_user_accounts (id)
);
create index if not exists idx_inv_resident_billing_branch on public.tbl_inv_resident_billing (branch_id);

-- ----------------------------------------------------------------------------
-- 3. Periods, closing snapshots, counters, idempotency
-- ----------------------------------------------------------------------------

create table if not exists public.tbl_inv_billing_periods (
  id                              bigint generated by default as identity primary key,
  branch_id                       bigint not null references public.tbl_branches ("BranchID"),
  period_month                    date not null check (period_month = date_trunc('month', period_month)::date),
  status                          text not null default 'OPEN' check (status in ('OPEN','LOCKED')),
  exceptions_reviewed_at          timestamptz,
  exceptions_reviewed_by_account  bigint references public.tbl_user_accounts (id),
  exceptions_reviewed_by_staff    text references public.tbl_staff ("StaffID"),
  locked_at                       timestamptz,
  locked_by_account               bigint references public.tbl_user_accounts (id),
  locked_by_staff                 text references public.tbl_staff ("StaffID"),
  reopen_count                    int not null default 0 check (reopen_count >= 0),
  created_at                      timestamptz not null default now(),
  unique (branch_id, period_month),
  check ((status = 'LOCKED') = (locked_at is not null))
);

create table if not exists public.tbl_inv_period_closing (   -- D-116; append-only, one set per lock
  billing_period_id  bigint not null references public.tbl_inv_billing_periods (id),
  branch_id          bigint not null references public.tbl_branches ("BranchID"),
  lock_seq           int not null,
  product_id         bigint not null references public.tbl_inv_products (id),
  location_id        bigint references public.tbl_inv_locations (id),   -- NULL row = pool total
  resident_id        bigint references public.tbl_residents (id),
  qty                numeric(18,4) not null,
  value              numeric(18,4),                                     -- pool and in-transit rows only
  in_transit_transfer_id bigint,   -- set: goods dispatched to another branch, not received by month end (D-153)
  created_at         timestamptz not null default now(),
  check ((location_id is null) = (value is not null))
);
create unique index if not exists uq_inv_period_closing on public.tbl_inv_period_closing
  (billing_period_id, lock_seq, product_id, location_id, resident_id, in_transit_transfer_id) nulls not distinct;
create index if not exists idx_inv_period_closing_branch on public.tbl_inv_period_closing (branch_id, billing_period_id);

create table if not exists public.tbl_inv_counters (
  branch_id   bigint not null references public.tbl_branches ("BranchID"),
  doc_type    text not null check (doc_type in ('TXN','RCV','TRF','REQ','CNT','ADJ','EXP')),
  year        int not null check (year between 2000 and 2999),   -- KL year of posting (D-129)
  last_no     int not null default 0 check (last_no >= 0),
  primary key (branch_id, doc_type, year)
);  -- number format <BranchCode>-<DOC>-<YYYY>-<000123>

create table if not exists public.tbl_inv_idempotency (   -- D-110
  key           uuid primary key,
  rpc           text not null,
  account_id    bigint not null references public.tbl_user_accounts (id),
  request_hash  bytea not null,
  result        jsonb not null,
  created_at    timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 4. Ledger (source of truth)
