-- ============================================================================
-- 11. Lock everything down before this transaction commits (audit V-1)
-- ============================================================================
-- The live default ACL gives anon/authenticated ALL on every new table and
-- EXECUTE on every new function, and PostgREST sees new objects at once. So
-- every inventory file ends by calling fn_inv_lockdown(): RLS on for every
-- tbl_inv_* table and NO privilege for PUBLIC, anon, authenticated or
-- service_role on any inventory table, view, sequence or function. Nothing is
-- reachable through the API until 013_inventory_grants.sql grants exactly what
-- is intended. Each file is therefore safe on its own, even if the next file
-- is never applied. (Re-running any file revokes the API grants again until
-- 013 is re-run: fail closed.)
create or replace function public.fn_inv_lockdown()
returns void language plpgsql set search_path = '' as $$
declare
  r record;
begin
  for r in
    select c.relname, c.relkind from pg_catalog.pg_class c
      join pg_catalog.pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind in ('r','v','m','S')
       and (c.relname like 'tbl\_inv\_%' or c.relname like 'v\_inv\_%')
  loop
    if r.relkind = 'r' then
      execute format('alter table public.%I enable row level security', r.relname);
    end if;
    if r.relkind = 'S' then
      execute format('revoke all on sequence public.%I from public, anon, authenticated, service_role', r.relname);
    else
      execute format('revoke all on table public.%I from public, anon, authenticated, service_role', r.relname);
    end if;
  end loop;
  for r in
    select p.oid::regprocedure as sig from pg_catalog.pg_proc p
      join pg_catalog.pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and (p.proname like 'fn\_inv\_%' or p.proname like 'inv\_%')
  loop
    execute format('revoke all on function %s from public, anon, authenticated, service_role', r.sig);
  end loop;
end $$;

select public.fn_inv_lockdown();

commit;
