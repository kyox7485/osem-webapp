create table if not exists public.tbl_inv_txns (
  id                           bigint generated by default as identity primary key,
  txn_no                       text not null unique,
  txn_type                     text not null check (txn_type in (
    'OPENING_BALANCE','RECEIPT','ISSUE','INTERNAL_TRANSFER','TRANSIT_ALLOCATE','TRANSIT_RELEASE',
    'BRANCH_TRANSFER_OUT','BRANCH_TRANSFER_IN','RETURN_FROM_ISSUE','RETURN_TO_SUPPLIER',
    'DAMAGED_EXPIRED','ADJUSTMENT','REVERSAL')),
  branch_id                    bigint not null references public.tbl_branches ("BranchID"),
  txn_date                     date not null,                                   -- KL business date
  billing_period_id            bigint not null references public.tbl_inv_billing_periods (id),
  posted_at                    timestamptz not null default clock_timestamp(),
  performed_by_staff           text not null references public.tbl_staff ("StaffID"),
  posted_by_account            bigint not null references public.tbl_user_accounts (id),
  approved_by_account          bigint references public.tbl_user_accounts (id),
  approved_by_staff            text references public.tbl_staff ("StaffID"),
  reason_code                  text check (reason_code in ('DAMAGED','EXPIRED','COUNT_VARIANCE','FOUND','LOST',
    'TRANSFER_DISCREPANCY','DATA_ENTRY','WRONG_RESIDENT','WRONG_PRODUCT','WRONG_QTY','WRONG_COST','DISCHARGED',
    'DECEASED','NO_LONGER_REQUIRED','WRONG_ALLOCATION','OTHER')),
  remarks                      text check (length(remarks) <= 500),
  expense_note                 text check (length(expense_note) <= 200),       -- OSEM-expense issues (Q-19)
  negative_stock_confirmed     boolean not null default false,
  inactive_resident_confirmed  boolean not null default false,
  sanity_confirmed             boolean not null default false,                 -- D-109
  reverses_txn_id              bigint unique references public.tbl_inv_txns (id),
  correction_of_txn_id         bigint references public.tbl_inv_txns (id),
  cascade_of_txn_id            bigint references public.tbl_inv_txns (id),     -- D-124
  source_doc_type              text check (source_doc_type in ('RECEIPT','BRANCH_TRANSFER','ADJUSTMENT')),
  source_doc_id                bigint,
  request_key                  uuid not null references public.tbl_inv_idempotency (key) deferrable initially deferred,
  created_at                   timestamptz not null default now(),
  check ((txn_type = 'REVERSAL') = (reverses_txn_id is not null)),
  check ((source_doc_type is null) = (source_doc_id is null))
);
create index if not exists idx_inv_txns_branch_date on public.tbl_inv_txns (branch_id, txn_date desc, id desc);
create index if not exists idx_inv_txns_period on public.tbl_inv_txns (billing_period_id);
create index if not exists idx_inv_txns_source on public.tbl_inv_txns (source_doc_type, source_doc_id);
create index if not exists idx_inv_txns_request on public.tbl_inv_txns (request_key);
create index if not exists idx_inv_txns_correction on public.tbl_inv_txns (correction_of_txn_id) where correction_of_txn_id is not null;

create table if not exists public.tbl_inv_txn_lines (
  id                 bigint generated by default as identity primary key,
  txn_id             bigint not null references public.tbl_inv_txns (id) deferrable initially deferred,
  line_no            smallint not null check (line_no > 0),
  branch_id          bigint not null references public.tbl_branches ("BranchID"),
  txn_date           date not null,                                             -- denormalised (D-115)
  txn_type           text not null,                                             -- denormalised
  location_id        bigint not null references public.tbl_inv_locations (id),
  location_kind      text not null check (location_kind in ('STORE','FLOOR','TRANSIT')),
  resident_id        bigint references public.tbl_residents (id),
  product_id         bigint not null references public.tbl_inv_products (id),
  qty_base           numeric(18,4) not null check (qty_base <> 0),
  uom_id             bigint not null references public.tbl_inv_uoms (id),
  uom_code           text not null,
  qty_entered        numeric(18,4) not null check (qty_entered > 0),           -- paid + FOC on receipts
  factor_to_base     numeric(18,6) not null check (factor_to_base >= 1),
  unit_cost          numeric(18,6) not null check (unit_cost >= 0),             -- per base uom
  value              numeric(18,4) not null,
  revaluation_value  numeric(18,4) not null default 0,
  cost_source        text not null check (cost_source in
    ('INPUT','LANDED','WAC','ORIGINAL','TRANSFER','MASTER_FALLBACK','PENDING_COST')),
  bucket_qty_after   numeric(18,4) not null,
  pool_qty_after     numeric(18,4) not null,
  pool_value_after   numeric(18,4) not null,
  pool_wac_after     numeric(18,6),
  pair_line_id       bigint references public.tbl_inv_txn_lines (id) deferrable initially deferred,
  source_line_id     bigint references public.tbl_inv_txn_lines (id) deferrable initially deferred,
  created_at         timestamptz not null default now(),
  unique (txn_id, line_no),
  check ((location_kind = 'TRANSIT') = (resident_id is not null)),
  check (abs(qty_base - sign(qty_base) * qty_entered * factor_to_base) < 0.00005)
);
create index if not exists idx_inv_lines_pool on public.tbl_inv_txn_lines (branch_id, product_id, id);
create index if not exists idx_inv_lines_bucket on public.tbl_inv_txn_lines (location_id, product_id, resident_id, id);
create index if not exists idx_inv_lines_date on public.tbl_inv_txn_lines (branch_id, txn_date, id);
create index if not exists idx_inv_lines_prod_date on public.tbl_inv_txn_lines (branch_id, product_id, txn_date);
create index if not exists idx_inv_lines_txn on public.tbl_inv_txn_lines (txn_id);
create index if not exists idx_inv_lines_source on public.tbl_inv_txn_lines (source_line_id) where source_line_id is not null;
create index if not exists idx_inv_lines_resident on public.tbl_inv_txn_lines (resident_id) where resident_id is not null;
create index if not exists idx_inv_lines_product_uom on public.tbl_inv_txn_lines (product_id, uom_id);

