-- True only inside fn_inv_purge_demo() run from the SQL editor (D-126, Q-21).
create or replace function public.fn_inv_purge_allowed(p_row jsonb) returns boolean
language plpgsql stable set search_path = '' as $$
declare
  v_branch bigint;
begin
  if coalesce(current_setting('inv.demo_purge', true), '') <> 'on' or session_user <> 'postgres' then
    return false;
  end if;
  v_branch := coalesce((p_row->>'branch_id')::bigint, (p_row->>'from_branch_id')::bigint,
    (p_row->>'owner_branch_id')::bigint,
    (select a.branch_id from public.tbl_user_accounts a where a.id = (p_row->>'account_id')::bigint),
    (select p.owner_branch_id from public.tbl_inv_products p where p.id = (p_row->>'product_id')::bigint));
  return v_branch is not null
     and exists (select 1 from public.tbl_branches b where b."BranchID" = v_branch and b.is_demo);
end $$;

-- Append-only tables: no UPDATE, no DELETE (except the demo purge).
create or replace function public.fn_inv_block_mutation() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'DELETE' and public.fn_inv_purge_allowed(to_jsonb(old)) then
    return old;
  end if;
  raise exception 'INV_IMMUTABLE: % on % is not allowed', tg_op, tg_table_name using errcode = 'P0001';
end $$;

create or replace function public.fn_inv_block_truncate() returns trigger
language plpgsql set search_path = '' as $$
begin
  raise exception 'INV_IMMUTABLE: TRUNCATE on % is not allowed', tg_table_name using errcode = 'P0001';
end $$;

-- Caches and counters: only the engine (inv.posting / inv.rebuild) writes.
create or replace function public.fn_inv_guard_cache() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'DELETE' and public.fn_inv_purge_allowed(to_jsonb(old)) then
    return old;
  end if;
  if coalesce(current_setting('inv.posting', true), '') = 'on'
     or (coalesce(current_setting('inv.rebuild', true), '') = 'on' and session_user = 'postgres') then
    if tg_op = 'DELETE' then
      raise exception 'INV_IMMUTABLE: DELETE on % is not allowed', tg_table_name using errcode = 'P0001';
    end if;
    return new;
  end if;
  raise exception 'INV_ENGINE_ONLY: % on % is only allowed inside the posting engine', tg_op, tg_table_name
    using errcode = 'P0001';
end $$;

-- Master data: never deleted (deactivate instead).
create or replace function public.fn_inv_block_delete() returns trigger
language plpgsql set search_path = '' as $$
begin
  if public.fn_inv_purge_allowed(to_jsonb(old)) then
    return old;
  end if;
  raise exception 'INV_IMMUTABLE: DELETE on % is not allowed (deactivate instead)', tg_table_name
    using errcode = 'P0001';
end $$;

-- Document tables: UPDATE only inside the engine and only through an explicit
-- per-table whitelist of columns and status transitions (D-144, F12).
create or replace function public.fn_inv_guard_document() returns trigger
language plpgsql set search_path = '' as $$
declare
  v_old jsonb := to_jsonb(old);
  v_new jsonb;
  v_changed text[];
  v_allowed text[];
  v_from text;
  v_to text;
  v_ok boolean := true;
begin
  if tg_op = 'DELETE' then
    if public.fn_inv_purge_allowed(v_old) then
      return old;
    end if;
    raise exception 'INV_IMMUTABLE: DELETE on % is not allowed', tg_table_name using errcode = 'P0001';
  end if;

  if coalesce(current_setting('inv.posting', true), '') <> 'on' then
    raise exception 'INV_ENGINE_ONLY: UPDATE on % is only allowed inside the posting engine', tg_table_name
      using errcode = 'P0001';
  end if;

  v_new := to_jsonb(new);
  -- generated columns are not yet computed in a BEFORE trigger: ignore them
  select coalesce(array_agg(k), '{}') into v_changed
    from jsonb_object_keys(v_new) k
   where v_new->k is distinct from v_old->k
     and k not in (select a.attname from pg_catalog.pg_attribute a
                    where a.attrelid = tg_relid and a.attgenerated <> '');
  v_from := v_old->>'status';
  v_to := v_new->>'status';

  case tg_table_name
    when 'tbl_inv_receipts' then
      v_allowed := array['is_voided','voided_by_txn_id','superseded_by_receipt_id'];
      v_ok := (not ('is_voided' = any(v_changed)) or (v_old->>'is_voided')::boolean = false)
          and (not ('voided_by_txn_id' = any(v_changed)) or v_old->'voided_by_txn_id' = 'null'::jsonb)
          and (not ('superseded_by_receipt_id' = any(v_changed)) or v_old->'superseded_by_receipt_id' = 'null'::jsonb);
    when 'tbl_inv_branch_transfers' then
      v_allowed := array['status','cancel_txn_id','updated_at'];
      v_ok := (v_from = v_to or (v_from, v_to) in (('DISPATCHED','RECEIVED'),('RECEIVED','DISPATCHED'),('DISPATCHED','CANCELLED')))
          and (not ('cancel_txn_id' = any(v_changed)) or (v_old->'cancel_txn_id' = 'null'::jsonb and v_to = 'CANCELLED'));
    when 'tbl_inv_billing_periods' then
      v_allowed := array['status','exceptions_reviewed_at','exceptions_reviewed_by_account','exceptions_reviewed_by_staff',
                         'locked_at','locked_by_account','locked_by_staff','reopen_count'];
      v_ok := case
        when v_from = 'LOCKED' and v_to = 'OPEN' then (v_new->>'reopen_count')::int = (v_old->>'reopen_count')::int + 1
        else (v_new->>'reopen_count')::int = (v_old->>'reopen_count')::int
             and (v_from = v_to or (v_from = 'OPEN' and v_to = 'LOCKED'))
             and (v_from = 'OPEN' or not (array['exceptions_reviewed_at'] <@ v_changed))
      end;
    when 'tbl_inv_stock_requests' then
      v_allowed := array['status','submitted_at','reviewed_by_account','reviewed_by_staff','reviewed_at','review_note',
                         'ordered_at','ordered_by_account','external_ref','expected_delivery_date','updated_at'];
      v_ok := v_from = v_to or (v_from, v_to) in (
        ('DRAFT','SUBMITTED'),('DRAFT','CANCELLED'),('SUBMITTED','APPROVED'),('SUBMITTED','REJECTED'),
        ('SUBMITTED','CANCELLED'),('APPROVED','ORDERED'),('APPROVED','CANCELLED'),('APPROVED','CLOSED'),
        ('ORDERED','PARTIALLY_RECEIVED'),('ORDERED','RECEIVED'),('ORDERED','CLOSED'),
        ('PARTIALLY_RECEIVED','RECEIVED'),('PARTIALLY_RECEIVED','CLOSED'));
    when 'tbl_inv_stock_request_lines' then
      v_allowed := array['approved_qty','requested_qty','supplier_id','remarks',
                         'closed_short_at','closed_short_by_account','closed_short_reason'];
      v_ok := not ('closed_short_at' = any(v_changed)) or v_old->'closed_short_at' = 'null'::jsonb;
    when 'tbl_inv_counts' then
      v_allowed := array['status','freeze_location','snapshot_line_id','started_at','submitted_at','investigated_by_staff',
                         'investigated_by_account','investigation_summary','closed_at','updated_at'];
      v_ok := (v_from = v_to or (v_from, v_to) in (
                 ('DRAFT','IN_PROGRESS'),('DRAFT','CANCELLED'),('IN_PROGRESS','SUBMITTED'),('IN_PROGRESS','CANCELLED'),
                 ('SUBMITTED','INVESTIGATED'),('SUBMITTED','CLOSED'),('SUBMITTED','CANCELLED'),('INVESTIGATED','CLOSED')))
          and (not ('snapshot_line_id' = any(v_changed)) or v_old->'snapshot_line_id' = 'null'::jsonb);
    when 'tbl_inv_count_lines' then
      v_allowed := array['expected_qty','posted_since_start','physical_qty','investigation_note'];
      v_ok := (not ('expected_qty' = any(v_changed)) or v_old->'expected_qty' = 'null'::jsonb)
          and (not ('posted_since_start' = any(v_changed)) or v_old->'posted_since_start' = 'null'::jsonb);
    when 'tbl_inv_adjustments' then
      v_allowed := array['status','decided_by_staff','decided_by_account','decided_at','decision_note','txn_id'];
      v_ok := v_from = 'PENDING' and v_to in ('APPROVED','REJECTED','CANCELLED');
    when 'tbl_inv_adjustment_lines' then
      v_allowed := array['qty_delta_base','count_line_id'];
      v_ok := exists (select 1 from public.tbl_inv_adjustments a
                      where a.id = (v_old->>'adjustment_id')::bigint and a.status = 'PENDING');
    else
      v_allowed := '{}';
      v_ok := false;
  end case;

  if not (v_changed <@ v_allowed) or not coalesce(v_ok, false) then
    raise exception 'INV_TRANSITION: UPDATE of % (%) is not an allowed transition', tg_table_name,
      array_to_string(v_changed, ',') using errcode = 'P0001';
  end if;
  return new;
end $$;

-- D-102, D-106, D-137: product invariants.
create or replace function public.fn_inv_guard_products() returns trigger
language plpgsql set search_path = '' as $$
declare
  v_is_service boolean;
  v_used boolean;
begin
  if new.owner_branch_id is not null
     and not exists (select 1 from public.tbl_branches b where b."BranchID" = new.owner_branch_id and b.is_demo) then
    raise exception 'INV_MASTER: owner_branch_id must be NULL or a demo branch (D-102)' using errcode = 'P0001';
  end if;
  if new.default_supplier_id is not null and not exists (
       select 1 from public.tbl_inv_suppliers s where s.id = new.default_supplier_id
       and (s.owner_branch_id is null or s.owner_branch_id = new.owner_branch_id)) then
    raise exception 'INV_MASTER: default supplier must be global or owned by the same demo branch' using errcode = 'P0001';
  end if;
  select c.is_service into v_is_service from public.tbl_inv_categories c where c.id = new.category_id;
  if new.is_stock_item = coalesce(v_is_service, false) then
    raise exception 'INV_MASTER: is_stock_item must be the opposite of category.is_service (D-137)' using errcode = 'P0001';
  end if;
  if tg_op = 'UPDATE' then
    if new.owner_branch_id is distinct from old.owner_branch_id then
      raise exception 'INV_MASTER: owner_branch_id cannot change' using errcode = 'P0001';
    end if;
    if new.base_uom_id <> old.base_uom_id or new.is_stock_item <> old.is_stock_item then
      v_used := exists (select 1 from public.tbl_inv_txn_lines l where l.product_id = old.id)
             or exists (select 1 from public.tbl_inv_receipt_lines r where r.product_id = old.id)
             or exists (select 1 from public.tbl_inv_charges c where c.product_id = old.id);
      if v_used then
        raise exception 'INV_MASTER: base UOM / stock-item flag cannot change once the product is used (D-106)'
          using errcode = 'P0001';
      end if;
    end if;
  end if;
  return new;
end $$;

-- D-106: factor_to_base is immutable once the (product, uom) is used.
create or replace function public.fn_inv_guard_product_uoms() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.product_id <> old.product_id or new.uom_id <> old.uom_id then
    raise exception 'INV_MASTER: product/uom of a conversion cannot change' using errcode = 'P0001';
  end if;
  if new.factor_to_base <> old.factor_to_base and (
       exists (select 1 from public.tbl_inv_txn_lines l where l.product_id = old.product_id and l.uom_id = old.uom_id)
    or exists (select 1 from public.tbl_inv_receipt_lines r where r.product_id = old.product_id and r.uom_id = old.uom_id)
    or exists (select 1 from public.tbl_inv_product_barcodes b where b.product_id = old.product_id and b.uom_id = old.uom_id)) then
    raise exception 'INV_MASTER: factor_to_base cannot change once used; add a new UOM instead (D-106)'
      using errcode = 'P0001';
  end if;
  return new;
end $$;

-- Deferred: the base row exists with factor 1, the purchase row exists, and
-- only the base row has factor 1 (D-106).
create or replace function public.fn_inv_check_product_uoms() returns trigger
language plpgsql set search_path = '' as $$
declare
  v_product bigint := case when tg_table_name = 'tbl_inv_products' then (to_jsonb(new)->>'id')::bigint
                           else (to_jsonb(new)->>'product_id')::bigint end;
  v_base bigint;
  v_purchase bigint;
begin
  select p.base_uom_id, p.purchase_uom_id into v_base, v_purchase from public.tbl_inv_products p where p.id = v_product;
  if not found then
    return null;
  end if;
  if not exists (select 1 from public.tbl_inv_product_uoms u
                 where u.product_id = v_product and u.uom_id = v_base and u.factor_to_base = 1 and u.is_active)
     or not exists (select 1 from public.tbl_inv_product_uoms u
                    where u.product_id = v_product and u.uom_id = v_purchase and u.is_active)
     or exists (select 1 from public.tbl_inv_product_uoms u
                where u.product_id = v_product and u.uom_id <> v_base and u.factor_to_base = 1 and u.is_active) then
    raise exception 'INV_MASTER: product % needs an active base UOM row with factor 1, an active purchase UOM row, and no other factor-1 row (D-106)', v_product
      using errcode = 'P0001';
  end if;
  return null;
end $$;

create or replace function public.fn_inv_guard_barcodes() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'UPDATE' and (new.barcode <> old.barcode or new.product_id <> old.product_id or new.uom_id <> old.uom_id) then
    raise exception 'INV_MASTER: a barcode row cannot be re-pointed; deactivate it and add a new one (D-128)'
      using errcode = 'P0001';
  end if;
  select p.owner_branch_id into new.owner_branch_id from public.tbl_inv_products p where p.id = new.product_id;
  return new;
end $$;

create or replace function public.fn_inv_guard_suppliers() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.owner_branch_id is not null
     and not exists (select 1 from public.tbl_branches b where b."BranchID" = new.owner_branch_id and b.is_demo) then
    raise exception 'INV_MASTER: owner_branch_id must be NULL or a demo branch (D-102)' using errcode = 'P0001';
  end if;
  if tg_op = 'UPDATE' and new.owner_branch_id is distinct from old.owner_branch_id then
    raise exception 'INV_MASTER: owner_branch_id cannot change' using errcode = 'P0001';
  end if;
  return new;
end $$;

-- D-135/D-140: only NUR branches have inventory settings and locations.
create or replace function public.fn_inv_guard_nur_branch() returns trigger
language plpgsql set search_path = '' as $$
begin
  if not exists (select 1 from public.tbl_branches b where b."BranchID" = new.branch_id and b."Function" = 'NUR') then
    raise exception 'INV_MASTER: inventory is only for NUR branches (D-135)' using errcode = 'P0001';
  end if;
  -- jsonb, not new.kind: this function serves two tables with different columns
  if tg_op = 'UPDATE' and (to_jsonb(new)->'branch_id' <> to_jsonb(old)->'branch_id'
                           or to_jsonb(new)->'kind' is distinct from to_jsonb(old)->'kind') then
    raise exception 'INV_MASTER: a location/settings row cannot change branch or kind' using errcode = 'P0001';
  end if;
  return new;
end $$;

create or replace function public.fn_inv_guard_stock_levels() returns trigger
language plpgsql set search_path = '' as $$
declare
  v_kind text;
begin
  select l.branch_id, l.kind into new.branch_id, v_kind from public.tbl_inv_locations l where l.id = new.location_id;
  if v_kind is null or v_kind not in ('STORE','FLOOR') then
    raise exception 'INV_MASTER: max levels exist only for STORE and FLOOR (D-24)' using errcode = 'P0001';
  end if;
  if not exists (select 1 from public.tbl_inv_products p where p.id = new.product_id and p.is_stock_item
                 and (p.owner_branch_id is null or p.owner_branch_id = new.branch_id)) then
    raise exception 'INV_MASTER: max level product must be a stock item visible to the branch' using errcode = 'P0001';
  end if;
  return new;
end $$;

