-- ============================================================================
-- 007 — General Inventory: tables, constraints, indexes, guard triggers
-- ============================================================================
-- Phase 1 of docs/inventory-design.md (rev 3). Additive only: no existing
-- table is altered; existing tables are only referenced by foreign keys.
--
--   007_inventory_schema.sql     tables + guard triggers            (this file)
--   008_inventory_access.sql     scope/capability helpers, RLS, views
--   009_inventory_engine.sql     posting engine (internal fn_inv_* functions)
--   010_inventory_rpc_stock.sql  stock-movement RPCs
--   011_inventory_rpc_admin.sql  reversal/correction, service charges, periods
--   012_inventory_seed.sql       UOMs, categories, locations, branch settings
--   013_inventory_grants.sql     ALL grants/revokes + read-back (re-run after
--                                every inventory migration)
--
-- Apply in order 007 → 013 in a quiet window. Each file is one transaction and
-- can be re-run.
-- Rollback (pre-go-live only): migration/scripts/rollback_inventory_v1.sql
-- Tests: `npm run test:inventory` in webapp/ (PGlite, never production).
--
-- Conventions (D-10, D-112, D-114):
--   * every name is prefixed tbl_inv_ / fn_inv_ / inv_ / v_inv_
--   * vocabularies are text + CHECK, not enums
--   * every branch-scoped table (children included) carries branch_id
--   * ids are "generated by default" so the engine can pre-allocate them
--   * clients never write: RLS is SELECT-only and grants are SELECT-only
-- ============================================================================

begin;

-- The FKs below take SHARE ROW EXCLUSIVE locks on tbl_branches, tbl_staff,
-- tbl_residents and tbl_user_accounts until COMMIT: fail fast instead of
-- queueing behind (and blocking) app traffic (audit P1-15).
set local lock_timeout = '5s';

-- D-133: SQL detects demo branches with tbl_branches.is_demo, the app with
-- BranchCode = 'DEMO' (getDemoBranchIds). Refuse to install if they differ.
do $$
begin
  if exists (
    select 1 from public.tbl_branches b
    where b.is_demo is distinct from (b."BranchCode" = 'DEMO')
  ) then
    raise exception 'INV_INSTALL: tbl_branches.is_demo does not match BranchCode = ''DEMO'' (D-133)';
  end if;
end $$;

-- ----------------------------------------------------------------------------
-- 1. Master data (org-wide; owner_branch_id is only ever a demo branch, D-102)
-- ----------------------------------------------------------------------------

create table if not exists public.tbl_inv_uoms (
  id              bigint generated by default as identity primary key,
  code            text not null unique check (code ~ '^[A-Z0-9_]{1,12}$'),
  name            text not null check (length(btrim(name)) between 1 and 60),
  name_ms         text check (length(name_ms) <= 60),
  allow_fraction  boolean not null default false,
  is_active       boolean not null default true,
  created_at      timestamptz not null default now()
);

-- D-137: is_service marks the one non-stock category (Service).
create table if not exists public.tbl_inv_categories (
  id          bigint generated by default as identity primary key,
  code        text not null unique check (code ~ '^[A-Z0-9_]{1,24}$'),
  name        text not null check (length(btrim(name)) between 1 and 60),
  name_ms     text check (length(name_ms) <= 60),
  is_service  boolean not null default false,
  sort_order  int not null default 0,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.tbl_inv_suppliers (
  id                  bigint generated by default as identity primary key,
  owner_branch_id     bigint references public.tbl_branches ("BranchID"),   -- NULL = global (D-102)
  name                text not null check (length(btrim(name)) between 1 and 120),
  name_key            text generated always as (lower(regexp_replace(btrim(name), '\s+', ' ', 'g'))) stored,
  contact_person      text check (length(contact_person) <= 120),
  phone               text check (length(phone) <= 40),
  email               text check (length(email) <= 120),
  address             text check (length(address) <= 400),
  notes               text check (length(notes) <= 500),
  is_active           boolean not null default true,
  created_by_account  bigint not null references public.tbl_user_accounts (id),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  updated_by_account  bigint references public.tbl_user_accounts (id)
);
create unique index if not exists uq_inv_suppliers_name
  on public.tbl_inv_suppliers (coalesce(owner_branch_id, 0), name_key);

-- D-136: no goods_class — Inventory is the only stock/billing system for
-- OSEM-bought goods. D-137: is_stock_item = NOT category.is_service.
create table if not exists public.tbl_inv_products (
  id                   bigint generated by default as identity primary key,
  owner_branch_id      bigint references public.tbl_branches ("BranchID"),  -- NULL = global; demo only
  sku                  text not null check (sku ~ '^[A-Za-z0-9._-]{1,40}$'),
  name                 text not null check (length(btrim(name)) between 1 and 160),
  description          text check (length(description) <= 1000),
  category_id          bigint not null references public.tbl_inv_categories (id),
  is_stock_item        boolean not null default true,
  base_uom_id          bigint not null references public.tbl_inv_uoms (id),   -- immutable once used (D-106)
  purchase_uom_id      bigint not null references public.tbl_inv_uoms (id),
  default_supplier_id  bigint references public.tbl_inv_suppliers (id),
  standard_unit_cost   numeric(18,6) check (standard_unit_cost between 0 and 100000),  -- per base; fallback only
  is_chargeable        boolean not null default true,                        -- false: RESIDENT charge blocked (D-121)
  charge_price         numeric(12,4) check (charge_price between 0 and 100000),        -- per base; NULL → PRICE_PENDING
  default_max_store    numeric(18,4) check (default_max_store >= 0),         -- D-101
  default_max_floor    numeric(18,4) check (default_max_floor >= 0),
  is_active            boolean not null default true,
  created_by_account   bigint not null references public.tbl_user_accounts (id),
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  updated_by_account   bigint references public.tbl_user_accounts (id),
  check (is_stock_item or (default_max_store is null and default_max_floor is null))
);
create unique index if not exists uq_inv_products_sku
  on public.tbl_inv_products (coalesce(owner_branch_id, 0), sku);
create index if not exists idx_inv_products_name_trgm
  on public.tbl_inv_products using gin (name public.gin_trgm_ops);
create index if not exists idx_inv_products_category on public.tbl_inv_products (category_id);

create table if not exists public.tbl_inv_product_uoms (
  product_id      bigint not null references public.tbl_inv_products (id),
  uom_id          bigint not null references public.tbl_inv_uoms (id),
  factor_to_base  numeric(18,6) not null check (factor_to_base >= 1),   -- base = smallest issuable unit (D-106)
  is_active       boolean not null default true,
  created_at      timestamptz not null default now(),
  primary key (product_id, uom_id)
);

create table if not exists public.tbl_inv_product_barcodes (
  id                  bigint generated by default as identity primary key,
  barcode             text not null check (barcode ~ '^[\x21-\x7E]{3,64}$'),
  product_id          bigint not null,
  uom_id              bigint not null,
  owner_branch_id     bigint references public.tbl_branches ("BranchID"),   -- copied from the product
  is_active           boolean not null default true,
  created_by_account  bigint not null references public.tbl_user_accounts (id),
  created_at          timestamptz not null default now(),
  foreign key (product_id, uom_id) references public.tbl_inv_product_uoms (product_id, uom_id)
);
create unique index if not exists uq_inv_barcode_active
  on public.tbl_inv_product_barcodes (coalesce(owner_branch_id, 0), barcode) where is_active;   -- D-128
create index if not exists idx_inv_barcodes_product on public.tbl_inv_product_barcodes (product_id, uom_id);

